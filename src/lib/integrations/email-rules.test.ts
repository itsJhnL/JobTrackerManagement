/** Same structure as a real Indeed Apply confirmation (tokens removed). */
const INDEED_HTML = `
<html><head><style>.x{color:red}</style></head><body>
<div style="display:none">We&#39;ll help you get started &zwnj; &zwnj; &zwnj; &#8204; &#847;</div>
<table><tr><td><p>Application submitted</p></td></tr>
<tr><td><a href="https://apply.indeed.com/indeedapply/confirmemail/viewjob?iaUid=1k70gcpreh9d7802&amp;apiToken=SECRET&amp;next=http%3A%2F%2Fph.indeed.com%2Fjob%2Fai-automation-engineer-e42408c2a6590729">AI Automation Engineer (Remote)</a></td></tr>
<tr><td><a href="http://ph.indeed.com/cmp/Chartrequest?campaignid=IAconfirm">ChartRequest</a></td></tr>
<tr><td>- Remote</td></tr>
<tr><td>49 reviews</td></tr>
<tr><td><p>The following items were sent to ChartRequest. Good luck!</p></td></tr>
<tr><td>&bull; Application</td></tr><tr><td>&bull; Resume</td></tr>
<tr><td><p>Next steps</p></td></tr>
<tr><td><p>The employer or job advertiser may reach out to you about your application.</p></td></tr>
<tr><td><p>Please do not reply directly to this autogenerated email message. If you have any questions or concerns about your application, please contact Indeed .</p></td></tr>
</table></body></html>`;

const INDEED_PLAIN = `Your application has been submitted. Good luck!
If you notice an error in your application, please Contact Indeed <https://apply.indeed.com/indeedapply/confirmemail/contactus?iaUid=1k70gcpreh9d7802&apiToken=SECRET>
------
Indeed - one search. all jobs.`;

function indeedInput(over: Partial<RuleInput> = {}): RuleInput {
  return {
    from_email: "indeedapply@indeed.com",
    from_name: "Indeed Apply",
    subject: "Indeed Application: AI Automation Engineer (Remote)",
    text: bodyText(INDEED_PLAIN, INDEED_HTML),
    links: extractLinks(INDEED_HTML),
    bulk: false,
    received_at: "2026-11-09T21:36:58.000Z",
    account_email: "me@example.com",
    ...over,
  };
}

function input(over: Partial<RuleInput>): RuleInput {
  return {
    from_email: "someone@example.com",
    subject: "",
    text: "",
    received_at: "2026-11-09T00:00:00.000Z",
    account_email: "me@example.com",
    ...over,
  };
}

describe("email content", () => {
  it("uses the HTML body when the plain part is a stub", () => {
    const text = bodyText(INDEED_PLAIN, INDEED_HTML);
    expect(text).toContain("The following items were sent to ChartRequest");
    expect(text).not.toMatch(/&zwnj;|‌|͏|color:red/);
  });

  it("keeps the plain body when it is the richer one", () => {
    const plain = "Hi John, thanks for applying. ".repeat(20);
    expect(bodyText(plain, "<p>Hi</p>")).toBe(plain.trim());
  });

  it("keeps meeting links when the HTML version is used", () => {
    const html =
      '<p>Your interview is confirmed for Monday at 10am. Join here: <a href="https://meet.google.com/abc-defg-hij">Join</a></p><a href="https://track.example/unsub">Unsubscribe</a>';
    const text = bodyText("Interview confirmed", html);
    expect(text).toContain("https://meet.google.com/abc-defg-hij");
    expect(text).not.toContain("track.example");
  });

  it("decodes HTML entities in subjects", () => {
    expect(
      cleanSubject("Bluedog &ndash; Software QA Engineer &ndash; John Leo Bruno"),
    ).toBe("Bluedog – Software QA Engineer – John Leo Bruno");
    expect(cleanSubject("")).toBe("(no subject)");
  });
});

describe("Indeed application confirmations", () => {
  it("extracts title, company, location, posting URL, job key and reference", () => {
    const c = parseIndeedConfirmation(indeedInput());
    expect(c).toEqual({
      platform: "Indeed",
      company: "ChartRequest",
      job_title: "AI Automation Engineer (Remote)",
      location: "Remote",
      job_url: "https://ph.indeed.com/job/ai-automation-engineer-e42408c2a6590729",
      job_key: "e42408c2a6590729",
      reference: "1k70gcpreh9d7802",
      applied_at: "2026-11-09T21:36:58.000Z",
    });
  });

  it("never stores Indeed's tokenised tracking link", () => {
    const c = parseIndeedConfirmation(indeedInput());
    expect(JSON.stringify(c)).not.toContain("apiToken");
  });

  it("routes to Applications, not the Inbox", () => {
    const d = preClassify(indeedInput());
    expect(d?.destination).toBe("applications");
    expect(d?.kind).toBe("application_confirmation");
    expect(reviewStatusFor(d!.destination)).toBe("confirmed");
  });

  it("keeps it in the Inbox when the company cannot be read", () => {
    const d = preClassify(indeedInput({ text: INDEED_PLAIN, links: [] }));
    expect(d?.kind).toBe("application_confirmation");
    expect(d?.destination).toBe("inbox");
  });

  it("does not treat other Indeed mail as a confirmation", () => {
    // A rejection from Indeed: same domain, no "application submitted" wording.
    expect(
      parseIndeedConfirmation(
        input({
          from_email: "noreply@indeed.com",
          subject: "An update on your application from ClientBase Pte Ltd",
          text: "Thank you for applying to the Full Stack Developer position at ClientBase Pte Ltd. Unfortunately, your application was not selected.",
        }),
      ),
    ).toBeNull();
    // Confirmation wording from a non-Indeed sender is not an Indeed confirmation.
    expect(
      parseIndeedConfirmation(indeedInput({ from_email: "fake@indeed-jobs.example" })),
    ).toBeNull();
  });

  it("handles postings on the employer's own site and a missing location", () => {
    const html = `<p>Application submitted</p><p><a href="https://apply.indeed.com/indeedapply/confirmemail/viewjob?iaUid=abc123&amp;apiToken=SECRET&amp;next=https%3A%2F%2Fgorillacommerce.applytojob.com%2Fapply%2FTE9YCNHTkA%2FFull-Stack-Developer%3Fsource%3DINDE">Full Stack Developer</a></p>
<p><a href="http://ph.indeed.com/cmp/Gorilla-Commerce">Gorilla Commerce</a></p><p>- +</p>
<p>The following items were sent to Gorilla Commerce. Good luck!</p>`;
    const c = parseIndeedConfirmation(
      indeedInput({
        subject: "Indeed Application: Full Stack Developer",
        text: bodyText("Your application has been submitted.", html),
        links: extractLinks(html),
      }),
    );
    expect(c).toMatchObject({
      company: "Gorilla Commerce",
      job_title: "Full Stack Developer",
      location: null,
      job_url:
        "https://gorillacommerce.applytojob.com/apply/TE9YCNHTkA/Full-Stack-Developer",
      job_key: null,
    });
  });

  it("reads job keys from both URL shapes", () => {
    expect(
      indeedJobKey("https://ph.indeed.com/viewjob?jk=246c2ca217ba8b03&from=share"),
    ).toBe("246c2ca217ba8b03");
    expect(
      indeedJobKey("http://ph.indeed.com/job/full-stack-developer-e42408c2a6590729"),
    ).toBe("e42408c2a6590729");
    expect(
      indeedJobKey("https://ph.indeed.com/job/senior-full-stack-developer-848246"),
    ).toBe(null);
  });
});

describe("job alerts", () => {
  it.each([
    [
      "donotreply@jobalert.indeed.com",
      "Front-End Developer (React.js, Remote) at AMAGI. 21 more developer jobs",
    ],
    ["donotreply@match.indeed.com", "Senior Programmer @ Translarity, Inc."],
    ["jobalerts-noreply@linkedin.com", "Frontend Developer job at HiJob.work"],
    [
      "noreply@glassdoor.com",
      "Junior Web Developer at American Oncology Network and 6 more jobs in Remote, US for you. Apply Now.",
    ],
    [
      "noreply@glassdoor.com",
      "Cook Medical Inc is hiring for Software Engineer 1, Full-Stack. Apply Now.",
    ],
    ["noreply@glassdoor.com", "New jobs in Addison, TX. Apply Now."],
  ])("filters %s: %s", (from, subject) => {
    const d = preClassify(
      input({ from_email: from, subject, text: "Jobs picked for you" }),
    );
    expect(d?.destination).toBe("filtered");
    expect(d?.category).toBe("job_alert");
  });

  it("does not rely on the sender alone: personal mail from an alert domain goes to the AI", () => {
    expect(
      isJobAlert(
        input({
          from_email: "noreply@glassdoor.com",
          subject: "New jobs in Addison, TX",
          text: "Thank you for applying. We would like to invite you to an interview.",
        }),
      ),
    ).toBe(false);
  });

  it("does not filter a company's own email that merely mentions jobs", () => {
    expect(
      isJobAlert(
        input({
          from_email: "talent@acme.example",
          subject: "Acme is hiring: next steps for your application",
          text: "Your application moved forward.",
        }),
      ),
    ).toBe(false);
  });

  it("needs bulk mail or a job board for subject-only matches", () => {
    const base = { from_email: "news@shop.example", subject: "New jobs at our store" };
    expect(isJobAlert(input(base))).toBe(false);
    expect(isJobAlert(input({ ...base, bulk: true }))).toBe(true);
  });
});

describe("own mail", () => {
  it("filters messages sent from the connected address", () => {
    const d = preClassify(
      input({ from_email: "Me@Example.com", subject: "Re: Interview Availability" }),
    );
    expect(d?.destination).toBe("filtered");
    expect(d?.category).toBe("sent_by_you");
  });
});

describe("routing after the AI", () => {
  const noMatch = { applicationId: null, confidence: 0, reason: "No confident match" };

  it("keeps interview invitations and recruiter mail in the Inbox", () => {
    for (const kind of [
      "interview_invitation",
      "recruiter_response",
      "rejection",
      "job_offer",
      "interview_reschedule",
      "other_recruiting",
    ] as const) {
      expect(
        routeAnalysis(
          { kind, confidence: 0.9, company: "Acme", job_title: "Dev" },
          input({}),
          noMatch,
        ).destination,
      ).toBe("inbox");
    }
  });

  it("saves a plain application receipt to Applications", () => {
    const d = routeAnalysis(
      {
        kind: "application_confirmation",
        confidence: 0.95,
        company: "Penbrothers",
        job_title: "Full Stack Python Web Developer",
      },
      input({
        from_email: "talentacquisition@penbrothers.com",
        text: "Thank you for your interest in the Full Stack Python Web Developer position at Penbrothers. We appreciate you taking the time to apply. Please follow us on our LinkedIn page.",
      }),
      noMatch,
    );
    expect(d.destination).toBe("applications");
    expect(d.confirmation?.company).toBe("Penbrothers");
    expect(d.confirmation?.platform).toBe("Email");
  });

  it("keeps a 'confirmation' that asks a question in the Inbox", () => {
    const d = routeAnalysis(
      {
        kind: "application_confirmation",
        confidence: 0.6,
        company: null,
        job_title: "Website Developer / Marketing",
      },
      input({
        from_email: "support@onlinejobs.ph",
        text: "Thank You for applying, do you know how to build a website on Wordpress and host website on Hostinger? If so, the website must have a modern look.",
      }),
      noMatch,
    );
    expect(d.destination).toBe("inbox");
    expect(d.kind).toBe("recruiter_response");
  });

  it("keeps a confirmation without company or title in the Inbox", () => {
    expect(
      routeAnalysis(
        {
          kind: "application_confirmation",
          confidence: 0.9,
          company: null,
          job_title: "Dev",
        },
        input({ text: "We received your application." }),
        noMatch,
      ).destination,
    ).toBe("inbox");
  });

  it("filters confident not-recruiting mail with its category", () => {
    const d = routeAnalysis(
      {
        kind: "not_recruiting",
        confidence: 0.95,
        company: null,
        job_title: null,
        filter_category: "marketing",
      },
      input({}),
      noMatch,
    );
    expect(d).toMatchObject({ destination: "filtered", category: "marketing" });
  });

  it("never hides mail from a known contact or company domain", () => {
    const d = routeAnalysis(
      { kind: "not_recruiting", confidence: 0.99, company: null, job_title: null },
      input({ from_email: "julie@themightymo.com" }),
      { applicationId: "app-1", confidence: 0.9, reason: "sender is a saved contact" },
    );
    expect(d.destination).toBe("inbox");
  });

  it("keeps uncertain not-recruiting calls in the Inbox", () => {
    expect(
      routeAnalysis(
        { kind: "not_recruiting", confidence: 0.5, company: null, job_title: null },
        input({}),
        noMatch,
      ).destination,
    ).toBe("inbox");
  });

  it("falls back to 'other' for an unknown filter category", () => {
    expect(
      routeAnalysis(
        {
          kind: "not_recruiting",
          confidence: 0.9,
          company: null,
          job_title: null,
          filter_category: "weird",
        },
        input({}),
        noMatch,
      ).category,
    ).toBe("other");
  });
});

describe("helpers", () => {
  it("detects requests to the candidate", () => {
    expect(asksCandidateToAct("Please reply with your availability.")).toBe(true);
    expect(asksCandidateToAct("Can you start Monday?")).toBe(true);
    expect(
      asksCandidateToAct(
        "Your application was received. If you have any questions or concerns, please contact Indeed.",
      ),
    ).toBe(false);
    expect(asksCandidateToAct("Have questions? Visit our help center.")).toBe(false);
  });

  it("names job platforms from the sender", () => {
    expect(platformFromSender("support@onlinejobs.ph")).toBe("OnlineJobs.ph");
    expect(platformFromSender("indeedapply@indeed.com")).toBe("Indeed");
    expect(platformFromSender("hr@acme.example")).toBeNull();
  });
});
